/**
 * merge_lore.mjs — SchreckNET expansion assembler.
 * Loads assets/js/lore_part_*.js (window.LORE_PART_*), dedupes by id (last file wins),
 * writes assets/js/lore_data.js (window.LORE_DB) and derives one NVIDIA photo prompt
 * per character, merging idempotently into image_prompts.json (by file name).
 * Usage: node scripts/merge_lore.mjs
 */
import { readFileSync, writeFileSync, readdirSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const HERE = dirname(fileURLToPath(import.meta.url));
const JS = join(HERE, '..', 'assets', 'js');
const ROOT = join(HERE, '..');

const shim = {};
const parts = readdirSync(JS).filter((f) => /^lore_part_.*\.js$/.test(f)).sort();
const clans = Object.create(null);
const bloodlines = Object.create(null);
const antitribu = Object.create(null);

for (const f of parts) {
  const code = readFileSync(join(JS, f), 'utf8');
  // eslint-disable-next-line no-new-func
  new Function('window', code)(shim);
  for (const k of Object.keys(shim)) {
    if (!k.startsWith('LORE_PART_')) continue;
    const db = shim[k];
    // same clan id across parts → concatenate chars (dedupe by char id, last wins)
    for (const c of db.clans || []) {
      if (!clans[c.id]) { clans[c.id] = c; continue; }
      const seen = new Set((clans[c.id].chars || []).map((ch) => ch.id));
      clans[c.id].chars = (clans[c.id].chars || []).concat((c.chars || []).filter((ch) => !seen.has(ch.id)));
    }
    for (const b of db.bloodlines || []) {
      if (!bloodlines[b.id]) { bloodlines[b.id] = b; continue; }
      const seen = new Set((bloodlines[b.id].chars || []).map((ch) => ch.id));
      bloodlines[b.id].chars = (bloodlines[b.id].chars || []).concat((b.chars || []).filter((ch) => !seen.has(ch.id)));
    }
    for (const a of db.antitribu || []) antitribu[a.id] = a;
  }
}

const clanList = Object.values(clans);
const blList = Object.values(bloodlines);
const atList = Object.values(antitribu);

const loreJs =
  '// AUTO-GENERATED by scripts/merge_lore.mjs — DO NOT EDIT BY HAND.\n' +
  '// Source of truth: assets/js/lore_part_*.js\n' +
  'window.LORE_DB = ' + JSON.stringify({ updated: new Date().toISOString(), clans: clanList, bloodlines: blList, antitribu: atList }, null, 2) + ';\n';
writeFileSync(join(JS, 'lore_data.js'), loreJs);

// ---- derive photo prompts (idempotent merge by file name) ----
// User directive: portraits must be DARK FANTASY — animalistic, deformed, clearly
// vampiric, heavily varied (no model-slop sameness). Deterministic per-char
// variation seeded by char id: same char always regenerates stable, but every
// char gets its own style + features + composition.
const MONSTROUS = new Set(['nosferatu', 'nagaraja', 'samedi']);

function hashStr(s) {
  let h = 2166136261;
  for (let i = 0; i < s.length; i++) { h ^= s.charCodeAt(i); h = Math.imul(h, 16777619); }
  return h >>> 0;
}

const STYLES = [
  'Dark fantasy oil painting, baroque chiaroscuro, cracked varnish texture, candlelit crypt gloom',
  'Gothic copperplate engraving style portrait, heavy black ink hatching, aged parchment tone',
  'Tarnished daguerreotype photograph, severe 19th century studio, silver-plate stains and scratches',
  'Brutal torchlight on wet stone, soot shadows, dripping condensation, harsh single flame from below',
  'Cold moonlight through a barred window, blue-grey palette, drifting dust, deep black corners',
  'Bioluminescent sewer gloom, sickly green underglow, wet brick and standing water reflections',
  'Blood-and-ash palette, embers floating in darkness, scorched ritual chamber',
  'Fog-drenched gaslight alley at night, amber lamp flare, rain-slick darkness',
  'Ritual candle circle in an ossuary, walls of skulls, warm bone tones against black',
  'Gutter-level harsh contrast, desaturated greens, grainy surveillance texture'
];
const FEATURES = [
  'feline slit-pupil eyes', 'elongated hollow canine fangs', 'wolfish heavy jaw', 'large bat-like ears',
  'dark branching veins under translucent waxen skin', 'eyes set unnaturally far apart',
  'gaunt hollow cheeks and thin bloodless lips', 'faint gill slits along the throat',
  'small curved ram horns', 'reptilian vertical pupils', 'long yellowed claw-like nails',
  'skin like cracked porcelain', 'mouth slightly too wide with too many teeth',
  'ridged predator brow', 'neck tendons taut like cables'
];
const MFEATS = [
  'gaunt hairless scalp with skin stretched tight over the skull', 'sunken milky eyes and yellowed fangs',
  'wet grey-green necrotic flesh', 'rat-like muzzle with rows of small teeth',
  'furless rat tail twisting out of the spine', 'bloated ghoulish gut under torn clothing',
  'flesh threaded with pale parasite worms', 'cluster of tiny dark eyes across one cheek',
  'stitched corpse seams across the jaw', 'translucent grey skin showing dark branching veins',
  'hunched vulture neck with a bare throat sac', 'whisker follicles fused into the upper lip',
  'oversized clawed hands dragging the ground', 'mange patches of thin mangy fur',
  'lipless mouth locked in a wide grin', 'bone horns pushing through the forehead skin'
];
const ANGLES = [
  'extreme close-up on the face', 'three-quarter portrait, chest up', 'low angle looking up at the figure',
  'shot from below by gutter light', 'profile emerging half-lit from shadow', 'over-the-shoulder glance back at the viewer'
];

function pick3(h, arr) {
  const n = arr.length;
  const set = [...new Set([h % n, (h >> 4) % n, (h >> 8) % n])];
  while (set.length < 3) set.push((set[set.length - 1] + 1) % n);
  return set.map((i) => arr[i]);
}

const prompts = [];
const kindreds = clanList.concat(blList, atList);
for (const k of kindreds) {
  const ugly = MONSTROUS.has(k.id) || /^(nosferatu|nagaraja|samedi)_antitribu$/.test(k.id);
  for (const ch of k.chars || []) {
    if (!ch.photo) continue;
    const h = hashStr(String(ch.id || ch.name));
    const place = (ch.location && (ch.location.place || '')) || '';
    const city = (ch.location && (ch.location.city || '')) || '';
    const base =
      STYLES[h % STYLES.length] + '. Character portrait of ' + ch.name + ', known as "' + (ch.alias || 'the nameless') + '", a ' +
      (ch.gen || 'elder') + '-generation vampire of the ' + k.name + ' bloodline, era: ' + (ch.era || 'modern nights') +
      '. Setting: ' + place + (city ? ', ' + city : '');
    const feats = pick3(h, FEATURES).join(', ');
    const mfeats = pick3(h, MFEATS).join(', ');
    const angle = ANGLES[(h >> 12) % ANGLES.length];
    const tail = ugly
      ? '. Composition: ' + angle + '. RPG dark-fantasy monster plate, NOT a human portrait: this is a hybrid horror, part vampire, part ghoul, part rat-beast, part walking corpse — ' + mfeats + ', plus ' + feats + '. Body horror that reflects the curse of the Blood. Grotesque bestiary-style dark fantasy, painterly and repulsive, absolutely not a beautiful human face. 35mm film grain, photorealistic horror, no text, no letters, no watermark'
      : '. Composition: ' + angle + '. The subject is a vampire — a wrong, predatory hybrid of an attractive person and a fresh corpse: ' + feats + '. Ghoulish distortion under the skin, shadowed predator gaze, uncanny dark fantasy, painterly, never a generic glamour portrait or a smooth AI-slop face. 35mm film grain, photorealistic, no text, no letters, no watermark';
    prompts.push({ file: String(ch.photo).replace('assets/img/', ''), size: '1024x1024', prompt: base + tail });
  }
}

// ---- sewer bestiary prompts (dark fantasy field-guide plates) ----
const beastCode = readFileSync(join(JS, 'bestiary_data.js'), 'utf8');
const beastShim = {};
// eslint-disable-next-line no-new-func
new Function('window', beastCode)(beastShim);
const beasts = (beastShim.BESTIARY_DB && beastShim.BESTIARY_DB.beasts) || [];
for (const be of beasts) {
  if (!be.photo) continue;
  const h = hashStr('beast:' + be.id + be.name);
  const feats = pick3(h, FEATURES).join(', ');
  const style = STYLES[h % STYLES.length];
  const angle = ANGLES[(h >> 12) % ANGLES.length];
  const base = style + '. Bestiary creature plate: ' + be.name + ', known as "' + (be.aka || '') + '" — ' + (be.cls || 'cryptid') + ', ' + (be.size || '') + ', recorded in the ' + (be.terrain || 'sewer mains') + '.';
  const tail = '. Composition: ' + angle + '. The creature must read as wet, real, and wrong — a naturalist horror study, ' + feats + '. Grotesque dark fantasy bestiary plate, painterly, absolutely not a cartoon monster or a generic kaiju. 35mm film grain, photorealistic horror, no text, no letters, no watermark';
  prompts.push({ file: String(be.photo).replace('assets/img/', ''), size: '1024x1024', prompt: base + tail });
}

const ipPath = join(ROOT, 'image_prompts.json');
const ip = JSON.parse(readFileSync(ipPath, 'utf8'));
const byFile = new Map(ip.images.map((p) => [p.file, p]));
for (const p of prompts) byFile.set(p.file, p);
ip.images = Array.from(byFile.values());
writeFileSync(ipPath, JSON.stringify(ip, null, 2) + '\n');

const charCount = kindreds.reduce((n, k) => n + ((k.chars || []).length), 0);
console.log('parts=' + parts.length + ' clans=' + clanList.length + ' bloodlines=' + blList.length + ' chars=' + charCount + ' prompts_total=' + ip.images.length);
