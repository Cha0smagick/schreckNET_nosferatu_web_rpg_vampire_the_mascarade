// one-shot: give every kindred_data.js entry a portrait; unmatched entries get new generated photos
import { readFileSync, writeFileSync, readdirSync } from 'fs';
import { join } from 'path';

const ROOT = process.cwd();
const JS = join(ROOT, 'assets', 'js');
const shim = {};
new Function('window', readFileSync(join(JS, 'lore_data.js'), 'utf8'))(shim);
const LORE = shim.LORE_DB;

const norm = (s) => String(s || '').toUpperCase().replace(/[^A-Z]/g, '');
const byName = new Map(), byAlias = new Map();
[...(LORE.clans || []), ...(LORE.bloodlines || []), ...(LORE.antitribu || [])].forEach((g) =>
  (g.chars || []).forEach((c) => {
    const base = String(c.photo || '').split('/').pop();
    if (!base) return;
    if (c.name && !byName.has(norm(c.name))) byName.set(norm(c.name), base);
    if (c.alias && !byAlias.has(norm(c.alias))) byAlias.set(norm(c.alias), base);
  })
);

// prompt-variation vocabulary (aligned with merge_lore.mjs engine)
const STYLES = [
  'Dark fantasy oil painting, baroque chiaroscuro, cracked varnish, candlelit crypt',
  'Gothic copperplate engraving, heavy black ink hatching, parchment',
  'Tarnished daguerreotype, 19th century studio, silver-plate stains',
  'Brutal torchlight on wet stone, soot shadows, single flame from below',
  'Cold moonlight through barred window, blue-grey, dust',
  'Bioluminescent sewer gloom, sickly green underglow, wet brick',
  'Blood-and-ash palette, embers, scorched ritual chamber',
  'Fog-drenched gaslight alley, amber lamp flare, rain'
];
const FEATS = [
  'feline slit-pupil eyes', 'elongated hollow canine fangs', 'wolfish heavy jaw',
  'dark branching veins under translucent waxen skin', 'eyes set unnaturally far apart',
  'gaunt hollow cheeks and thin bloodless lips', 'small curved ram horns',
  'long yellowed claw-like nails', 'skin like cracked porcelain',
  'mouth slightly too wide with too many teeth', 'ridged predator brow'
];
const MFEATS = [
  'rat-like muzzle with rows of small teeth', 'furless rat tail twisting out of the spine',
  'bloated ghoulish gut under torn clothing', 'flesh threaded with pale parasite worms',
  'stitched corpse seams across the jaw', 'hunched vulture neck with a bare throat sac',
  'oversized clawed hands', 'mange patches of thin mangy fur'
];
function hashStr(s) { let h = 2166136261; for (let i = 0; i < s.length; i++) { h ^= s.charCodeAt(i); h = Math.imul(h, 16777619); } return h >>> 0; }
function pick3(h, arr) { const n = arr.length; const set = [...new Set([h % n, (h >> 4) % n, (h >> 8) % n])]; while (set.length < 3) set.push((set[set.length - 1] + 1) % n); return set.map((i) => arr[i]); }

const kdShim = {};
new Function('window', readFileSync(join(JS, 'kindred_data.js'), 'utf8'))(kdShim);
const DB = kdShim.KINDRED_DB;
    const imgs = new Set(readdirSync(join(ROOT, 'assets', 'img')));
const ip = JSON.parse(readFileSync(join(ROOT, 'image_prompts.json'), 'utf8'));
const byFile = new Map(ip.images.map((p) => [p.file, p]));
for (const p of ip.images) if (/^k[0-9]+\.png$/.test(p.file)) byFile.delete(p.file); // drop collided junk from previous run

let matched = 0, generated = 0;
['vampires', 'ghouls', 'childer'].forEach((key) =>
  (DB[key] || []).forEach((r) => {
    if (r.portrait) return;
    const hit = byName.get(norm(r.name)) || byAlias.get(norm(r.alias)) || null;
    if (hit && imgs.has(hit)) { r.portrait = hit; matched++; return; }
    const file = 'k' + String(r.id || r.name || 'x').toLowerCase().replace(/[^a-z0-9]/g, '') + '.png';
    r.portrait = file;
    const h = hashStr(key + r.id + r.name);
    const style = STYLES[h % STYLES.length];
    const feats = pick3(h, FEATS).join(', ');
    const mf = pick3(h, MFEATS).join(', ');
    const kind = key === 'ghouls' ? 'an emaciated blood-bonded mortal ghoul servant' : key === 'childer' ? 'a fledgling vampire, childer, barely holding the Beast' : 'a vampire, wrong predatory hybrid of a person and a fresh corpse';
    const prompt =
      style + '. Character portrait of ' + (r.name || r.id) + ' (registry id ' + (r.id || '') + '), ' + kind +
      ' of clan ' + (r.clan || 'unknown') + ', recorded in ' + (r.city || 'no fixed city') +
      '. Composition: three-quarter portrait, chest up. ' + (key === 'vampires' ? 'Hybrid monster-leaning dark fantasy: ' + mf + ', ' : '') + feats + '. Uncanny grotesque dark fantasy, painterly, not a generic glamour portrait or a smooth AI-slop face. 35mm film grain, photorealistic horror, no text, no letters, no watermark';
    byFile.set(file, { file, size: '1024x1024', prompt });
    generated++;
  })
);

ip.images = Array.from(byFile.values());
writeFileSync(join(JS, 'kindred_data.js'),
  '// GENERATED by scripts/_fix_kindred_portraits.mjs - portraits mapped to LORE_DB, unmatched entries assigned generated photos. Do not hand-edit portraits.\n' +
  'window.KINDRED_DB = ' + JSON.stringify(DB, null, 1) + ';\n');
writeFileSync(join(ROOT, 'image_prompts.json'), JSON.stringify(ip, null, 2) + '\n');
console.log('matched=' + matched + ' generated=' + generated + ' prompts_total=' + ip.images.length);
