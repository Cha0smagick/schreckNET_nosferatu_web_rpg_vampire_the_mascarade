// merge_cities.mjs — fusiona cities_part_*.js en assets/js/cities_data.js (window.CITIES_DB)
// Escanea TODAS las propiedades del window shim de cada part y recolecta los arrays .cities.
import { readFileSync, writeFileSync, readdirSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const HERE = dirname(fileURLToPath(import.meta.url));
const JS = join(HERE, '..', 'assets', 'js');

function loadPart(file) {
  const code = readFileSync(join(JS, file), 'utf8');
  const window = {};
  const fn = new Function('window', code + ';');
  fn(window);
  return window;
}

const parts = readdirSync(JS).filter((f) => f.startsWith('cities_part_') && f.endsWith('.js')).sort();
const byId = new Map();
for (const f of parts) {
  const w = loadPart(f);
  let added = 0;
  for (const key of Object.keys(w)) {
    const v = w[key];
    if (v && Array.isArray(v.cities)) {
      for (const c of v.cities) { byId.set(c.id, c); added++; }
    }
  }
  console.log(f + ': +' + added);
}

const cities = Array.from(byId.values());
cities.sort((a, b) => (a.continent || '').localeCompare(b.continent || '') || a.name.localeCompare(b.name));
const db = { updated: new Date().toISOString().slice(0, 10), cities: cities };
const banner = '// cities_data.js — GENERATED by scripts/merge_cities.mjs — DO NOT EDIT BY HAND\n';
writeFileSync(join(JS, 'cities_data.js'), banner + 'window.CITIES_DB = ' + JSON.stringify(db, null, 1) + ';\n');
console.log('merged parts=' + parts.length + ' cities=' + cities.length);
